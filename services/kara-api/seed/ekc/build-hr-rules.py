NOISE = re.compile(r"^(تعداد صفحه|نحوه ی امحاء|تصويب|مدیر عامل \||نام و نام خانوداگی|تاريخ :|هر گونه تغيير|دستورالعمل .* / EKWI)")


def body_of(d) -> str:
    lines, started = [], False
    for el in d.element.body.iterchildren():
        if el.tag.endswith("}p"):
            t = Paragraph(el, d).text.strip()
            if not started and t == "هدف":
                started = True
            if started and t:
                lines.append(t)
        elif el.tag.endswith("}tbl") and started:
            for r in Table(el, d).rows:
                cells = list(dict.fromkeys(c.text.strip().replace("\n", " / ") for c in r.cells))
                lines.append(" | ".join(cells))
    return "\n".join(l for l in lines if not NOISE.match(l))


def header_of(d) -> str:
    out = []
    for s in d.sections:
        for t in s.header.tables:
            for r in t.rows:
                out.append(" | ".join(dict.fromkeys(c.text.strip() for c in r.cells)))
    return " || ".join(out)


def approval_of(d):
    """The sign-off table (prepared, checked, verified, approved) and its date, when the document has one."""
    for t in d.tables:
        rows = [[c.text.strip() for c in r.cells] for r in t.rows]
        flat = " ".join(" ".join(r) for r in rows)
        if "تصويب" in flat or "تصویب" in flat:
            names = [re.sub(r"^نام و نام خانوداگی:\s*", "", c) for r in rows for c in r if c.startswith("نام و نام")]
            roles = next((r for r in rows if any("مدیر عامل" in c for c in r)), [])
            iso, written = jalali(flat.split("تاريخ")[-1]) if "تاريخ" in flat else (None, None)
            return list(dict.fromkeys(names)), list(dict.fromkeys(roles)), iso, written
    return [], [], None, None


def main() -> None:
    items = []
    for f in sorted((HERE / "hr-rules").glob("*.docx")):
        d = docx.Document(str(f))
        code = f.stem                                     # EKWI-AD-001-08
        base = code.rsplit("-", 1)[0]                     # EKWI-AD-001
        meta = DOCS.get(base)
        if not meta:
            sys.exit(f"{f.name}: no summary in DOCS — write one first")
        head = header_of(d)
        created_iso, created = jalali(head.split("تاریخ ایجاد")[-1]) if "تاریخ ایجاد" in head else (None, None)
        names, roles, approved_iso, approved = approval_of(d)
        features = {"شماره سند": code, "ویرایش": code.rsplit("-", 1)[1], "مالک سند": "واحد سرمایه انسانی", "سطح محرمانگی": "سازمانی"}
        if created:
            features["تاریخ ایجاد"] = created
        if approved:
            features["تاریخ تصویب این ویرایش"] = approved
        if names and roles:
            # Roles run right to left in the table, as the names do.
            features["تهیه، تأیید و تصویب"] = "، ".join(f"{r}: {n}" for r, n in zip(roles, names) if r and n)
        items.append({
            "code": code,
            "name": meta["name"],
            "summary": meta["summary"],
            "body": body_of(d),
            "effectiveDate": approved_iso,
            "attributes": features,
            "file": f"hr-rules/{f.name}",
        })
        print(f"{code}: {len(items[-1]['body'])} chars, created {created}, approved {approved}")
    (HERE / "hr-rules.json").write_text(json.dumps(items, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
