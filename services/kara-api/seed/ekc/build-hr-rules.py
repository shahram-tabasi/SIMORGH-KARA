def j2g(jy: int, jm: int, jd: int) -> str:
    """Jalali to Gregorian (ISO date)."""
    jy += 1595
    days = -355668 + 365 * jy + (jy // 33) * 8 + ((jy % 33) + 3) // 4 + jd + ((jm - 1) * 31 if jm < 7 else (jm - 7) * 30 + 186)
    gy = 400 * (days // 146097)
    days %= 146097
    if days > 36524:
        days -= 1
        gy += 100 * (days // 36524)
        days %= 36524
        if days >= 365:
            days += 1
    gy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        gy += (days - 1) // 365
        days = (days - 1) % 365
    gd = days + 1
    leap = (gy % 4 == 0 and gy % 100 != 0) or gy % 400 == 0
    months = [0, 31, 29 if leap else 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    gm = 0
    while gm < 13 and gd > months[gm]:
        gd -= months[gm]
        gm += 1
    return f"{gy:04d}-{gm:02d}-{gd:02d}"


def jalali(text: str):
    """A Jalali date in a header (21/09/1396 or 1404/11/02): (iso, as written)."""
    m = re.search(r"(\d{4})/(\d{1,2})/(\d{1,2})", text)
    if m:
        y, mo, d = map(int, m.groups())
    else:
        m = re.search(r"(\d{1,2})/(\d{1,2})/(\d{4})", text)
        if not m:
            return None, None
        d, mo, y = map(int, m.groups())
    return j2g(y, mo, d), f"{y:04d}/{mo:02d}/{d:02d}"


